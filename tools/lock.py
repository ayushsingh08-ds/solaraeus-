"""Generate a pinned lockfile for the project's dependency closure.

Records the exact version of every direct dependency plus, as comments, the rest
of the installed closure -- so a fresh clone can reproduce the scientific stack
the golden master in ``tools/golden/baseline`` was captured against.

The pin list comes from ``pip freeze`` rather than ``importlib.metadata``:
``distributions()`` enumerates whatever happens to be on ``sys.path`` in the
*current* process, so running this file as a script yields a different list than
importing it (521 vs 516 distributions observed here).  ``pip freeze`` reports
the installed working set instead, which is what a lockfile must describe.

Usage
-----
    python tools/lock.py            # write requirements.lock
    python tools/lock.py --check    # fail if the active pins are stale
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LOCKFILE = REPO_ROOT / "requirements.lock"

# Direct dependencies declared in pyproject.toml (distribution names).  Keep in
# sync with [project.dependencies] and [project.optional-dependencies].
DIRECT = [
    "numpy",
    "scipy",
    "matplotlib",
    "shapely",
    "trimesh",
    "mapbox_earcut",
    "pyproj",
    "pandas",
    "scikit-learn",
    "pythermalcomfort",
    "psutil",
    "rasterio",
    "pillow",
    "pytest",
    "ruff",
    "mypy",
    "cupy-cuda12x",
]

HEADER = [
    "# Generated by tools/lock.py - do not edit by hand.",
    "# Pins the exact versions the golden master in tools/golden/baseline was",
    "# captured against. Regenerate with `make lock` after changing pyproject.toml.",
    "#",
    "# Install with:  pip install -r requirements.lock",
    "",
]


def canonical(name: str) -> str:
    """Normalise a distribution name the way PEP 503 does."""
    return re.sub(r"[-_.]+", "-", name).lower()


def installed_versions() -> dict[str, str]:
    """Return {canonical distribution name: version} for the installed working set.

    Raises RuntimeError if pip is unavailable, rather than silently producing a
    truncated lockfile.
    """
    proc = subprocess.run(
        [sys.executable, "-m", "pip", "freeze"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"`pip freeze` failed ({proc.returncode}): {proc.stderr.strip()[:200]}")

    out: dict[str, str] = {}
    for raw in proc.stdout.splitlines():
        line = raw.strip()
        if not line or line.startswith(("#", "-")):
            continue
        if "==" in line:
            name, _, version = line.partition("==")
        elif " @ " in line:
            # Editable/VCS installs: "name @ file:///..." or "name @ git+..."
            name, _, version = line.partition(" @ ")
            if "file://" in version:
                continue  # local editable install of this project: not a pin
            version = version.strip()
        else:
            continue
        out[canonical(name)] = version.strip()
    return out


def active_pins(versions: dict[str, str]) -> tuple[list[str], list[str]]:
    """Return (rendered active pin lines, names missing from the environment)."""
    lines: list[str] = []
    missing: list[str] = []
    for dist in sorted(DIRECT, key=canonical):
        key = canonical(dist)
        if key in versions:
            lines.append(f"{dist}=={versions[key]}")
        else:
            missing.append(dist)
    return lines, missing


def build_lockfile() -> str:
    """Render the lockfile text for the current environment."""
    versions = installed_versions()
    pins, missing = active_pins(versions)

    body = ["", "# --- transitive closure (informational, not installed by -r) ---"]
    seen = {canonical(d) for d in DIRECT}
    body += [f"# {key}=={versions[key]}" for key in sorted(versions) if key not in seen]

    tail: list[str] = []
    if missing:
        tail = ["", f"# WARNING: not installed in this environment: {', '.join(missing)}"]

    return "\n".join(HEADER + pins + body + tail) + "\n"


def parse_lockfile(text: str) -> dict[str, str]:
    """Return the *active* (uncommented) pins recorded in *text*."""
    pins: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "==" not in line:
            continue
        name, _, version = line.partition("==")
        pins[canonical(name)] = version.strip()
    return pins


def main() -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the active pins are stale")
    args = parser.parse_args()

    try:
        text = build_lockfile()
    except RuntimeError as exc:
        print(f"cannot generate the lockfile: {exc}", file=sys.stderr)
        return 2

    if args.check:
        if not LOCKFILE.exists():
            print(f"{LOCKFILE.name} is missing; run `make lock`", file=sys.stderr)
            return 1
        recorded = parse_lockfile(LOCKFILE.read_text(encoding="utf-8"))
        current = parse_lockfile(text)
        if recorded != current:
            drift = sorted(
                f"{n}: {recorded.get(n, '<absent>')} -> {current.get(n, '<absent>')}"
                for n in set(recorded) | set(current)
                if recorded.get(n) != current.get(n)
            )
            print(
                f"{LOCKFILE.name} is stale ({len(drift)} pin(s) drifted); run `make lock`",
                file=sys.stderr,
            )
            for item in drift[:20]:
                print(f"  {item}", file=sys.stderr)
            return 1
        print(f"{LOCKFILE.name} is up to date ({len(current)} active pins)")
        return 0

    LOCKFILE.write_text(text, encoding="utf-8", newline="\n")
    pins, _ = active_pins(installed_versions())
    print(f"wrote {LOCKFILE.relative_to(REPO_ROOT)} ({len(pins)} pinned distributions)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
